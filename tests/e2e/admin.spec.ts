import { test, expect } from "@playwright/test";

test("panel administra carta, QR e insumos con consumo y devolución", async ({ page, playwright, baseURL }) => {
  await page.goto("/");
  await expect(page.locator("body")).toHaveCSS("background-color", "rgb(255, 255, 255)");
  await expect(page.getByRole("link", { name: "Notificaciones", exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "Mi cuenta", exact: true }).click();
  await page.getByLabel("Correo", { exact: true }).fill("admin@restaurante.test");
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.SEED_PASSWORD!);
  await page.getByRole("button", { name: "Ingresar", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Pedidos", exact: true })).toBeVisible();
  const bell = page.getByRole("button", { name: "Notificaciones", exact: true });
  await expect(bell).toHaveCSS("min-height", "32px");
  await bell.click();
  await expect(page.getByRole("region", { name: "Notificaciones", exact: true })).toBeVisible();
  await bell.click();
  await expect(page.getByRole("region", { name: "Notificaciones", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Carta", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Agregar a la carta", exact: true })).toBeVisible();
  await page.screenshot({ path: ".cache/admin-carta.png", fullPage: true });
  await page.getByRole("button", { name: "Inventario", exact: true }).click();
  await expect(page.getByText("Existencias por unidad", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Mesas y QR", exact: true }).click();
  const tableSummary = page.locator("summary").filter({ hasText: "Agregar una mesa" });
  await expect(tableSummary.locator("svg.disclosure-chevron")).toBeVisible();
  await tableSummary.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("button", { name: "Agregar mesa y generar QR" })).toBeVisible();
  await page.keyboard.press("Enter");
  const tableTiles = page.locator(".mesa-tile");
  await tableTiles.nth(1).click();
  await expect(tableTiles.nth(1)).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("complementary", { name: /^Mesa / }).getByRole("button", { name: "Ver QR" })).toBeVisible();
  await page.screenshot({ path: ".cache/admin-mesas.png", fullPage: true });

  const admin = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { Origin: baseURL! }, storageState: await page.context().storageState() });
  const catalog = await (await admin.get("/api/v1/catalog")).json();
  const product = await (await admin.post("/api/v1/products", { data: { name: `QA Receta ${Date.now()}`, description: "Prueba de inventario", price: "10.00", categoryId: catalog.categories[0].id, station: "KITCHEN" } })).json();
  const ingredient = await (await admin.post("/api/v1/inventory", { data: { name: `QA Insumo ${Date.now()}`, unit: "kg", minimum: "1" } })).json();
  expect((await admin.post(`/api/v1/inventory/${ingredient.id}/movements`, { data: { quantity: "2.000", reason: "Entrada de prueba", kind: "ENTRADA" } })).status()).toBe(201);
  expect((await admin.put(`/api/v1/products/${product.id}/recipe`, { data: [{ ingredientId: ingredient.id, quantity: "0.500" }] })).status()).toBe(200);
  const table = await (await admin.post("/api/v1/tables", { data: { name: `INV-${Date.now()}`, zone: "Pruebas", seats: 2 } })).json();
  await admin.post(`/api/v1/tables/${table.id}/open`, { data: {} });
  // Pedido de cliente (sin sesión): queda por confirmar y el consumo se descuenta al confirmar.
  const guest = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { Origin: baseURL! } });
  const created = await guest.post("/api/v1/orders", { headers: { "Idempotency-Key": crypto.randomUUID() }, data: { tableToken: table.qrToken, items: [{ productId: product.id, quantity: 2, expectedPrice: "10.00" }] } });
  expect(created.status()).toBe(201);
  const order = (await created.json()).order;
  const stock = async () => (await (await admin.get("/api/v1/inventory")).json()).ingredients.find((i: { id: string }) => i.id === ingredient.id).stock;
  expect(Number(await stock())).toBe(2);
  const confirmed = await admin.post(`/api/v1/orders/${order.id}/transition`, { data: { action: "confirm", version: 0 } });
  expect(confirmed.status()).toBe(200);
  expect(Number(await stock())).toBe(1);
  await page.goto(`/panel?vista=tables&mesa=${table.id}`);
  await expect(page.getByText("Cierre pendiente de entrega o pago")).toBeVisible();
  const qrButton = page.getByRole("button", { name: "Ver QR", exact: true });
  await expect(qrButton).toHaveCSS("height", "32px");
  const takeOrder = page.getByRole("link", { name: "Tomar pedido", exact: true });
  expect((await takeOrder.boundingBox())!.width).toBeLessThan(150);

  expect((await admin.post(`/api/v1/orders/${order.id}/transition`, { data: { action: "confirm", version: 0 } })).status()).toBe(409);
  expect(Number(await stock())).toBe(1);
  const cancelled = await admin.post(`/api/v1/orders/${order.id}/transition`, { data: { action: "cancel", version: 1, reason: "Cancelación antes de cocinar" } });
  expect(cancelled.status()).toBe(200);
  expect(Number(await stock())).toBe(2);
  await admin.post(`/api/v1/tables/${table.id}/close`, { data: {} });
  await admin.patch(`/api/v1/tables/${table.id}`, { data: { active: false } });
  await admin.patch(`/api/v1/products/${product.id}`, { data: { active: false } });
  await page.getByRole("button", { name: "Reportes", exact: true }).click();
  await expect(page.getByText("Total cobrado registrado", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  const layout = await page.evaluate(() => ({ width: innerWidth, document: document.documentElement.scrollWidth, overflow: [...document.querySelectorAll("body *")].map(e => ({ tag: e.tagName, class: e.className.toString(), right: e.getBoundingClientRect().right, width: e.getBoundingClientRect().width })).filter(e => e.right > innerWidth + 1) }));
  expect(layout.document, JSON.stringify(layout)).toBeLessThanOrEqual(layout.width);
  await guest.dispose();
  await admin.dispose();
});
